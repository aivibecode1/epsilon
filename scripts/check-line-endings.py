#!/usr/bin/env python3
"""No tracked text file may carry CRLF endings (M231, ledger A9 follow-up).

## Why this exists

`.gitattributes` says `* text=auto eol=lf`, so git normalises endings **on commit** and
`git diff` shows a file whose working copy has CRLF as unchanged. That hides the one thing
that matters while you are editing: a CRLF working copy is a *different file* to every
tool that parses this repository's source.

The incident that made it a gate (M231). One edit was applied with PowerShell's
`WriteAllLines`, which writes CRLF on Windows. The next battery failed on:

    run_workspace_command has no `other` arm. That is expected only if it became
    exhaustive over the whole enum -- check that it was not made exhaustive by
    re-listing the variants the sibling executors own.

That message is about an architecture defect. The arm was present. The guard finds
it by parsing `commands.rs` and splitting on a `}` followed by a newline, and its
`map_or("", ...)` fallback turns "not found" into "the arm is empty" -- so a file
with CRLF endings reports as a dispatcher with no catch-all. The next thing a
reader would do is go looking for a routing bug that does not exist.

That is the argument for a gate rather than a habit: **the failure was legible, and
it pointed at the wrong subject.** This check fails in under a second, names the
file, and says which tool produced it.

## What it checks

Every tracked file that is not binary, for a `\r\n` anywhere in the first bytes it
reads. `.gitattributes` already decides which files are text (`*.png binary`), and
this check reads the same attribute file rather than guessing extensions a second time
— two lists that answer the same question can disagree, which is the mistake A12
records in the config layer.

## What it does not do

- It does not rewrite anything. A file is fixed where it was edited, not here.
- It does not check committed content. `git ls-files` plus a working-copy read is
  exactly "what is on this machine right now", which is the thing that bites.
"""

from __future__ import annotations

import subprocess
import sys
from pathlib import Path

REPO = Path(__file__).resolve().parent.parent

# Directories whose contents are not this repository's to police.
SKIP_DIRS = {
    ".git",
    "target",
    "references",  # the four reference harnesses, not committed by this repo
    "audit/history",  # superseded and deliberately unrepaired (AGENTS.md)
    # Battery logs are **regenerated by `gate.ps1` on every run** and are written with
    # the platform's newline, so they are CRLF in a Windows working copy by
    # construction. Nothing in the harness parses them -- they are read by people --
    # and their committed form is LF regardless, because `* text=auto eol=lf`
    # normalises on commit. Normalising them here would rewrite every recorded run
    # byte-for-byte on every run, which is the opposite of what an evidence file
    # should do.
    "audit/evidence",
}


def binary_suffixes() -> set[str]:
    """Extensions `.gitattributes` marks binary, so this check agrees with git."""
    suffixes: set[str] = set()
    attributes = REPO / ".gitattributes"
    if not attributes.is_file():
        return suffixes
    for raw in attributes.read_text(encoding="utf-8").splitlines():
        line = raw.strip()
        if not line or line.startswith("#"):
            continue
        parts = line.split()
        if len(parts) < 2 or parts[0].startswith("#"):
            continue
        pattern, attributes_list = parts[0], parts[1:]
        if "binary" in attributes_list or "-text" in attributes_list:
            suffixes.add(Path(pattern).suffix.lower())
    return suffixes


def tracked_files() -> list[str]:
    out = subprocess.run(
        ["git", "-C", str(REPO), "ls-files", "-z"],
        capture_output=True,
        check=True,
    )
    return [p for p in out.stdout.decode("utf-8").split("\0") if p]


def offenders(files: list[str], binary: set[str]) -> list[tuple[str, int]]:
    """`(path, line)` for each file carrying a CRLF, with the line it starts on.

    The line number is the whole point: "this file has CRLF" costs a hunt, "line 412"
    costs a look, and a file rewritten wholesale has thousands.
    """
    found: list[tuple[str, int]] = []
    for rel in files:
        if any(rel == d or rel.startswith(d + "/") for d in SKIP_DIRS):
            continue
        if Path(rel).suffix.lower() in binary:
            continue
        path = REPO / rel
        try:
            data = path.read_bytes()
        except OSError:
            continue
        if b"\r\n" not in data:
            continue
        line = data[: data.index(b"\r\n")].count(b"\n") + 1
        found.append((rel, line))
    return found


def main(argv: list[str]) -> int:
    quiet = "--quiet" in argv
    binary = binary_suffixes()
    files = tracked_files()
    bad = offenders(files, binary)

    if bad:
        print(f"check-line-endings: {len(bad)} tracked file(s) carry CRLF endings\n")
        for rel, line in bad[:40]:
            print(f"  {rel}:{line}")
        if len(bad) > 40:
            print(f"  ... and {len(bad) - 40} more")
        print(
            "\nThis repository is LF (`.gitattributes`: `* text=auto eol=lf`), and git"
            "\nnormalises on commit -- so `git diff` shows a CRLF working copy as"
            "\nUNCHANGED. That is why this is a gate: a source-parsing test then fails"
            "\nwith a message about something else entirely (M231: a dispatcher reported"
            "\nno catch-all arm because the file's CRLF endings broke a newline split)."
            "\n\nTo fix one: rewrite the file with LF endings -- in PowerShell,"
            "\n`[System.IO.File]::WriteAllText` with content whose newlines are LF,"
            "\nor `cargo fmt` for Rust sources. Do not commit a CRLF working copy."
        )
        return 1

    if not quiet:
        print(
            f"check-line-endings: {len(files)} tracked files, 0 with CRLF "
            f"({len(binary)} binary suffix(es) skipped)"
        )
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
