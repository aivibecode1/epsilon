//! Session log entries: the append-only JSONL vocabulary.
//!
//! Port of pi's `Entry` union (`harness/session/types.ts`) with two additions:
//! [`EntryKind::TurnEnd`] (typed sticky turn endings, from DSH) and the api-request hash on
//! message entries (Hermes' replay-fidelity invariant). The human transcript is the file;
//! model-visible history is a *derived view* that shadows compacted ranges.

use serde::{Deserialize, Serialize};

use crate::agent_event::TurnEndReason;
use crate::message::{Message, Usage};

/// One line in a session `.jsonl` file.
///
/// Storage assigns `seq`, `parent_id`, and `timestamp_ms` at append time; `id` is generated by
/// the caller. `parent_id` chains entries into the branch tree (pi's fork/navigate substrate).
///
/// M41: a session file is normally headed by a [`SessionHeader`] line (pi's
/// `{type:"session"}` first line) carrying the file format `version`, a stable
/// session `id`, the creation timestamp, the `cwd` the session started in, and the
/// optional `parent_session` id it was forked from. The header rides in its own
/// tagged variant so old headerless files still parse (they read as version 1)
/// and the reader can migrate forward.
#[derive(Debug, Clone, PartialEq, Serialize, Deserialize)]
#[serde(untagged)]
pub enum SessionLine {
    /// File header (first line of every new session file).
    Header(SessionHeader),
    /// A regular transcript entry.
    Entry(SessionEntry),
}

/// File format version written by this build (pi's `CURRENT_SESSION_VERSION`).
pub const CURRENT_SESSION_VERSION: u32 = 3;

/// First line of a session file (pi's `SessionHeader`).
///
/// `version` is `None` only when READING a v1 file (pi's v1 headers carry no
/// version field); everything this build writes stamps
/// [`CURRENT_SESSION_VERSION`].
#[derive(Debug, Clone, PartialEq, Serialize, Deserialize)]
pub struct SessionHeader {
    /// Discriminator (`"session"`), matching pi's `{type:"session"}` line.
    #[serde(rename = "type")]
    pub kind: SessionHeaderKind,
    /// File format version; absent on v1 files.
    #[serde(default, skip_serializing_if = "Option::is_none")]
    pub version: Option<u32>,
    /// Stable session id (`ses_...`).
    pub id: String,
    /// ISO-8601 creation timestamp.
    pub timestamp: String,
    /// Working directory the session started in (empty on v1 files).
    #[serde(default)]
    pub cwd: String,
    /// Id of the session this one was forked from, if any.
    #[serde(default, skip_serializing_if = "Option::is_none")]
    pub parent_session: Option<String>,
}

/// Discriminator for [`SessionHeader`] lines.
#[derive(Debug, Clone, Copy, PartialEq, Eq, Serialize, Deserialize)]
#[serde(rename_all = "snake_case")]
pub enum SessionHeaderKind {
    /// The only header kind (`"session"`).
    Session,
}

/// One transcript entry in a session `.jsonl` file.
///
/// Storage assigns `seq`, `parent_id`, and `timestamp_ms` at append time; `id` is generated by
/// the caller. `parent_id` chains entries into the branch tree (pi's fork/navigate substrate).
#[derive(Debug, Clone, PartialEq, Serialize, Deserialize)]
pub struct SessionEntry {
    /// Unique entry id (`ent_...`).
    pub id: String,
    /// File-assigned monotonic sequence number (0-based, gapless).
    pub seq: u64,
    /// Id of the previous entry on this lane; `None` only for the first entry.
    pub parent_id: Option<String>,
    /// Unix epoch milliseconds at append.
    pub timestamp_ms: u64,
    /// The payload.
    pub kind: EntryKind,
}

/// Payload kinds. Order of declaration mirrors pi for reviewability.
#[derive(Debug, Clone, PartialEq, Serialize, Deserialize)]
#[serde(tag = "type", rename_all = "snake_case")]
pub enum EntryKind {
    /// A transcript message (user/assistant/tool_result/custom).
    Message {
        /// The message itself.
        message: Message,
        /// SHA-256 of the exact provider payload that produced/consumed this message
        /// (Hermes' `api_content` invariant). Always set for assistant/tool-result entries
        /// once real providers are in play; `None` for harness-only messages.
        api_request_sha256: Option<String>,
    },
    /// Model selection changed mid-session.
    ModelChange {
        /// Provider identifier.
        provider: String,
        /// Model identifier.
        model_id: String,
    },
    /// Thinking/reasoning level changed.
    ThinkingLevelChange {
        /// Off/minimal/low/medium/high/xhigh/max (provider-clamped).
        level: String,
    },
    /// Active tool set changed.
    ActiveToolsChange {
        /// Names of tools now active.
        tools: Vec<String>,
    },
    /// Compaction landed: everything from the prior compaction point up to here is shadowed
    /// in the model view by `summary`; the human view keeps every line.
    Compaction {
        /// Summary text replacing shadowed history for the model.
        summary: String,
        /// Estimated tokens before compaction.
        tokens_before: u64,
        /// Recent messages kept verbatim after the summary.
        retained_tail: Vec<Message>,
        /// Files read/modified accumulated across compacted history (feeds future summaries).
        details: Option<serde_json::Value>,
        /// Usage of the summarization call(s).
        usage: Option<Usage>,
    },
    /// Summary of an abandoned branch created when navigating elsewhere.
    BranchSummary {
        /// Entry the abandoned branch started from.
        from_id: String,
        /// Summary text of the abandoned work.
        summary: String,
        /// Usage of the summarization call.
        usage: Option<Usage>,
    },
    /// Extension/harness state that never enters LLM context.
    Custom {
        /// Application discriminator.
        custom_type: String,
        /// Free-form payload.
        data: Option<serde_json::Value>,
    },
    /// Typed turn ending (Epsilon addition; see [`TurnEndReason::merge_sticky`]).
    TurnEnd {
        /// Why the run ended.
        reason: TurnEndReason,
    },
}

impl SessionHeader {
    /// Effective format version: v1 files carry no version field (pi parity).
    pub fn effective_version(&self) -> u32 {
        self.version.unwrap_or(1)
    }
}

impl SessionLine {
    /// Parse one JSONL line; `None` for blank lines (caller skips them).
    /// Malformed lines are an `Err` — the caller decides tail-vs-corruption.
    pub fn parse(line: &str) -> Option<Result<Self, serde_json::Error>> {
        if line.trim().is_empty() {
            return None;
        }
        Some(serde_json::from_str(line.trim_end()))
    }
}

impl SessionEntry {
    /// True when this entry contributes messages to the LLM-derived view.
    pub fn is_llm_visible(&self) -> bool {
        matches!(&self.kind, EntryKind::Message { message, .. } if message.is_llm_visible())
    }
}

#[cfg(test)]
mod tests {
    use super::*;
    use crate::content::UserContent;
    use crate::ids::new_id;
    use crate::message::{AssistantMessage, Message, StopReason, Usage, UserMessage};

    fn user_msg() -> Message {
        Message::User(UserMessage {
            id: new_id("msg"),
            timestamp_ms: 0,
            content: vec![UserContent::Text { text: "hi".into() }],
        })
    }

    #[test]
    fn entry_roundtrips_as_one_jsonl_line() {
        let entry = SessionEntry {
            id: new_id("ent"),
            seq: 3,
            parent_id: Some(new_id("ent")),
            timestamp_ms: 42,
            kind: EntryKind::Message {
                message: user_msg(),
                api_request_sha256: None,
            },
        };
        let line = serde_json::to_string(&entry).unwrap();
        assert!(!line.contains('\n'));
        assert_eq!(serde_json::from_str::<SessionEntry>(&line).unwrap(), entry);
    }

    #[test]
    fn header_line_parses_and_reports_version() {
        let header = SessionHeader {
            kind: SessionHeaderKind::Session,
            version: Some(CURRENT_SESSION_VERSION),
            id: new_id("ses"),
            timestamp: "2026-09-04T00:00:00.000Z".into(),
            cwd: "/tmp".into(),
            parent_session: None,
        };
        let line = serde_json::to_string(&header).unwrap();
        assert!(line.contains("\"type\":\"session\""));
        let parsed = SessionLine::parse(&line).unwrap().unwrap();
        let SessionLine::Header(back) = parsed else {
            panic!("header must parse as Header, got {parsed:?}");
        };
        assert_eq!(back, header);
        assert_eq!(back.effective_version(), CURRENT_SESSION_VERSION);

        // v1 files carry no version field at all.
        let v1 = r#"{"type":"session","id":"ses_x","timestamp":"t","cwd":""}"#;
        let SessionLine::Header(v1h) = SessionLine::parse(v1).unwrap().unwrap() else {
            panic!("v1 header must parse");
        };
        assert_eq!(v1h.version, None);
        assert_eq!(v1h.effective_version(), 1);
        // …but v1 still doesn't collide with entries (no `seq` field).
        assert!(matches!(
            SessionLine::parse(v1).unwrap().unwrap(),
            SessionLine::Header(_)
        ));
    }

    #[test]
    fn compaction_entry_carries_retained_tail() {
        let assistant = Message::Assistant(AssistantMessage {
            id: new_id("msg"),
            timestamp_ms: 1,
            provider: "faux".into(),
            model_id: "m".into(),
            content: vec![],
            stop_reason: StopReason::EndTurn,
            error_message: None,
            usage: Usage::default(),
        });
        let entry = SessionEntry {
            id: new_id("ent"),
            seq: 9,
            parent_id: None,
            timestamp_ms: 2,
            kind: EntryKind::Compaction {
                summary: "did stuff".into(),
                tokens_before: 123456,
                retained_tail: vec![assistant],
                details: None,
                usage: None,
            },
        };
        assert!(!entry.is_llm_visible());
        let json = serde_json::to_string(&entry).unwrap();
        assert!(json.contains("\"type\":\"compaction\""));
    }
}
